#!/usr/bin/env python3
"""Reconcile context-first draft poses with shipped clips; never infer native timing."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'docs/animation/runtime-coverage.json'
TABLE = ROOT / 'docs/animation/RUNTIME_COVERAGE.md'


def report():
    paths = ['art/animation/context/manifest.json', 'assets/models/motion.json']
    catalog, motion = [json.loads((ROOT / p).read_text()) for p in paths]
    poses = {p['id']: p for p in catalog['poses']}
    sequences = catalog['use_cases']
    clips = []
    for clip in motion['clips']:
        clips.append({
            'name': clip['name'], 'pose_ids': clip['keys'],
            'authored_clip_duration_s': sum(clip['durations']),
            'timing_basis': 'RoadDash authored tuning; not recovered native durations',
            'context_sequences': sorted({s['id'] for s in sequences
                                         if set(s['pose_ids']) & set(clip['keys'])}),
            'runtime_only_pose_ids': [p for p in clip['keys'] if p not in poses],
        })
    used = {p for c in clips for p in c['pose_ids']}
    return {
        'schema_version': 1,
        'source_sha256': {p: hashlib.sha256((ROOT / p).read_bytes()).hexdigest() for p in paths},
        'scope': 'Part 02 source-to-runtime coverage audit; no pose or timing approval',
        'context_pose_count': len(poses), 'runtime_clip_count': len(clips),
        'runtime_clips': clips,
        'context_sequences': [{
            'id': s['id'], 'actor': s['actor'], 'state': s['state'],
            'pose_ids': s['pose_ids'], 'phase_labels': s['phase_labels'],
            'entry_pose': s['entry_pose'], 'exit_pose': s['exit_pose'],
            'interrupts': s['interrupts'], 'review': s['review'],
            'notes': s['notes'],
            'held_contacts': {str(p): poses[p]['held_contacts'] for p in s['pose_ids']},
            'source_sprite_slots': {str(p): poses[p]['source_slots'] for p in s['pose_ids']},
            'runtime_clips': [c['name'] for c in clips if set(c['pose_ids']) & set(s['pose_ids'])],
        } for s in sequences],
        'unplayed_context_pose_ids': sorted(set(poses) - used),
        'limitations': [
            'Key membership proves coverage only, not reachability, correct action side or approved silhouettes.',
            'Runtime playback can retime/blend clips; authored duration is not observed action latency.',
            'Procedural walk/idle/terrain/lean blends and physics-driven crashes are not standalone clips.',
            'Club forehand clips are first-weapon runtime candidates; remaining weapon/police sequences stay explicit drafts.',
            'Source slots can be view variants; this report never converts them into temporal phases.',
            'Full catalog acceptance still requires unresolved caller, support, hand and visual review.',
        ],
    }


def markdown(data):
    lines = [
        '# Animation A — source-to-runtime coverage', '',
        'Generated by tools/report_animation_coverage.py. All source poses remain drafts; '
        'clip membership does not prove approved appearance or gameplay reachability.', '',
        f"{len(data['context_sequences'])} sequences / {data['context_pose_count']} context poses / "
        f"{data['runtime_clip_count']} shipped clips. "
        f"{len(data['unplayed_context_pose_ids'])} context poses are absent from standalone clips.", '',
        '[Context catalog](context/CATALOG.md) · [Draft gallery](../../art/animation/context/gallery/index.html) · '
        '[Machine report](runtime-coverage.json) · [Next review](NEXT_REVIEW.md)', '',
        '| Context sequence | Draft pose IDs | Source sprite slots | Matching shipped clips | Review |',
        '| --- | --- | --- | --- | --- |',
    ]
    for seq in data['context_sequences']:
        slots = sorted({n for values in seq['source_sprite_slots'].values() for n in values})
        lines.append(f"| {seq['id']} | {', '.join(map(str, seq['pose_ids']))} | "
                     f"{', '.join(map(str, slots)) or 'Original authored pose'} | "
                     f"{', '.join(seq['runtime_clips']) or 'No standalone clip'} | {seq['review']} |")
    lines += ['', '## Shipped clips', '',
              'Authored durations below can be retimed by playback. They are not native timings or measured action latency.', '',
              '| Clip | Pose IDs | Authored duration (s) | Runtime-only keys |',
              '| --- | --- | --- | --- |']
    for clip in data['runtime_clips']:
        lines.append(f"| {clip['name']} | {', '.join(map(str, clip['pose_ids']))} | "
                     f"{clip['authored_clip_duration_s']:.2f} | "
                     f"{', '.join(map(str, clip['runtime_only_pose_ids'])) or 'None'} |")
    lines += ['', 'Procedural locomotion/lean and physical crashes also use other paths. '
              'Missing specialist/weapon playback remains explicit; do not revive superseded V1 source labels.', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    data = report()
    outputs = {OUTPUT: json.dumps(data, indent=2) + '\n', TABLE: markdown(data)}
    for path, content in outputs.items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit('Animation coverage stale: run python3 tools/report_animation_coverage.py')
        else:
            path.write_text(content)
            print(path)
    if args.check:
        print('Source-to-runtime animation coverage is current')


if __name__ == '__main__':
    main()
